export function useI18n() {
  const language = usePapyrusStore((state) => state.language);
  const setLanguage = usePapyrusStore((state) => state.setLanguage);
  const toggleLanguage = usePapyrusStore((state) => state.toggleLanguage);
  const t = translations[language];

  return { language, setLanguage, toggleLanguage, t };
}
