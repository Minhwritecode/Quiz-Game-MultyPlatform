def clear_scene():
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete(use_global=False)
    for block_col in (
        bpy.data.actions,
        bpy.data.meshes,
        bpy.data.armatures,
        bpy.data.materials,
    ):
        for item in list(block_col):
            block_col.remove(item)


def make_mat(name, color, metallic=0.08, roughness=0.38, emission=None, emission_strength=1.0):
    mat = bpy.data.materials.new(name=name)
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    if bsdf:
        bsdf.inputs["Base Color"].default_value = color
        bsdf.inputs["Metallic"].default_value = metallic
        bsdf.inputs["Roughness"].default_value = roughness
        if emission is not None:
            if "Emission Color" in bsdf.inputs:
                bsdf.inputs["Emission Color"].default_value = emission
                bsdf.inputs["Emission Strength"].default_value = emission_strength
            elif "Emission" in bsdf.inputs:
                bsdf.inputs["Emission"].default_value = emission
    return mat


def add_part(parts_list, obj, mat, bone_name, smooth=True):
    """Apply transforms into mesh vertices in world space and tag with bone_name."""
    bpy.context.view_layer.objects.active = obj
    obj.select_set(True)
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
    obj.select_set(False)
    obj.data.materials.clear()
    obj.data.materials.append(mat)
    if smooth:
        for poly in obj.data.polygons:
            poly.use_smooth = True
    vg = obj.vertex_groups.new(name=bone_name)
    vg.add(list(range(len(obj.data.vertices))), 1.0, "REPLACE")
    parts_list.append(obj)


def join_and_skin(parts_list, arm_obj, joined_name):
    bpy.ops.object.select_all(action="DESELECT")
    for p in parts_list:
        p.select_set(True)
    bpy.context.view_layer.objects.active = parts_list[0]
    bpy.ops.object.join()
    mesh_obj = bpy.context.active_object
    mesh_obj.name = joined_name
    mesh_obj.parent = arm_obj
    mod = mesh_obj.modifiers.new(name="Armature", type="ARMATURE")
    mod.object = arm_obj
    return mesh_obj


def export_glb_and_ts(glb_filename, ts_filename, export_const_name, with_animations=True):
    os.makedirs(MODELS_DIR, exist_ok=True)
    os.makedirs(TS_DIR, exist_ok=True)
    glb_path = os.path.join(MODELS_DIR, glb_filename)
    bpy.ops.export_scene.gltf(
        filepath=glb_path,
        export_format="GLB",
        export_yup=True,
        export_apply=False,
        export_skins=True,
        export_animations=with_animations,
        export_animation_mode="NLA_TRACKS" if with_animations else "ACTIONS",
        export_materials="EXPORT",
        export_draco_mesh_compression_enable=False,
    )
    with open(glb_path, "rb") as f:
        b64 = base64.b64encode(f.read()).decode("ascii")
    ts_path = os.path.join(TS_DIR, ts_filename)
    with open(ts_path, "w", encoding="utf-8") as f:
        f.write(
            f"// Auto-generated by scripts/blender/build_rpg_suite.py — Vibrant Stylized PBR GLB\n"
            f"export const {export_const_name} = 'data:model/gltf-binary;base64,{b64}';\n"
        )
    size_kb = os.path.getsize(glb_path) / 1024.0
    print(f"[Papyrus Blender] Exported {glb_filename} ({size_kb:.1f} KB) -> {ts_filename}")


